#!/usr/bin/env python3
"""Writes kmoni_tab5/quake_snapshot.h: every earthquake of intensity 3 or stronger in JMA's
long-term intensity database, packed for flash. Run it to bring the built-in list up to date.

usage: make_quake_snapshot.py
"""
import calendar, datetime, json, os, re, sys, time, urllib.request

DB = "https://www.data.jma.go.jp/eqdb/data/shindo/api/"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "kmoni_tab5", "quake_snapshot.h")
RANKS = {"震度３": 3, "震度４": 4, "震度５弱": 5, "震度５強": 6, "震度６弱": 7, "震度６強": 8, "震度７": 9, "震度５": 5 | 0x80, "震度６": 7 | 0x80}
EPOCH = calendar.timegm((1919, 1, 1, 0, 0, 0))


def search(to_date, to_time):
    body = (f"mode=search&dateTimeF[]=1919-01-01&dateTimeF[]=00:00&dateTimeT[]={to_date}&dateTimeT[]={to_time}"
            "&mag[]=0.0&mag[]=9.9&dep[]=0&dep[]=999&epi[]=99&pref[]=99&city[]=99&station[]=99&obsInt=1&maxInt=3"
            "&additionalC=true&Sort=S0&Comp=C0&seisCount=false&observed=false")
    return json.loads(urllib.request.urlopen(urllib.request.Request(DB, body.encode()), timeout=90).read())["res"]


def sortable_time(ot):
    """Older records can be vaguer. Gives the time and what's known of it, as in quake_data.h."""
    month = re.fullmatch(r"(\d{4})年(\d\d)月", ot)
    if month:
        return f"{month[1]}/{month[2]}/01 00:00:00", 2
    hour = re.fullmatch(r"(\d{4}/\d\d/\d\d \d\d)時", ot)
    if hour:
        return f"{hour[1]}:00:00", 1
    return (ot + ":00" if len(ot) == 16 else ot[:19]), 0


def main():
    # The database refuses a search past its newest day, and says which day that is.
    answer = search(datetime.date.today().isoformat(), "23:59")
    through = datetime.date.today().isoformat()
    if isinstance(answer, str):
        through = re.search(r"\d{4}-\d{2}-\d{2}", answer).group()

    # It returns the newest 1000 of a search, so walk backwards from the oldest row each time.
    rows, to_date, to_time = {}, through, "23:59"
    while True:
        batch = search(to_date, to_time)
        if isinstance(batch, str):
            sys.exit("database said: " + batch)
        rows.update((e["id"], e) for e in batch)
        print(f"{len(rows)} rows, back to {batch[-1]['ot'][:10]}")
        if len(batch) < 1000:
            break
        to_date, to_time = batch[-1]["ot"][:10].replace("/", "-"), batch[-1]["ot"][11:16]
        time.sleep(1)

    ordered = sorted(rows.values(), key=lambda e: (sortable_time(e["ot"])[0], e["id"]), reverse=True)
    names = sorted({e["name"] or "" for e in ordered})
    index = {n: i for i, n in enumerate(names)}
    lines = []
    for e in ordered:
        # An id is usually the time to the second, but not always: 20160416040053 is 04:00:52.
        ot, precision = sortable_time(e["ot"])
        when = calendar.timegm(time.strptime(ot, "%Y/%m/%d %H:%M:%S"))
        id_delta = calendar.timegm(time.strptime(e["id"], "%Y%m%d%H%M%S")) - when
        if time.strftime("%Y/%m/%d %H:%M:%S", time.gmtime(when)) != ot:
            sys.exit(f"can't pack: {e['id']} {e['ot']}")
        seconds = when - EPOCH
        mag = e["mag"] or ""
        if mag[:1].isdigit() and not re.fullmatch(r"\d\.\d", mag):
            sys.exit(f"unexpected magnitude: {e['id']} {mag}")
        mag10 = round(float(mag) * 10) if mag[:1].isdigit() else -1
        dep = e["dep"] or ""
        depth = int(re.match(r"\d+", dep).group()) if dep[:1].isdigit() else -1
        has = bool(e["lat"] and e["lon"]) and (float(e["lat"]) != 0 or float(e["lon"]) != 0)  # "0.0000" is unknown
        lat, lon = (round(float(e["lat"]) * 100), round(float(e["lon"]) * 100)) if has else (-32768, -32768)
        lines.append(f"{{{seconds},{lat},{lon},{index[e['name'] or '']},{mag10},{depth},{RANKS[e['maxI']] | precision << 4},{id_delta}}},")

    with open(OUT, "w") as f:
        f.write("// Generated by tools/make_quake_snapshot.py; don't edit by hand.\n"
                "// Source: Japan Meteorological Agency, 震度データベース. Processed: packed for flash, intensity 3 and up.\n"
                "#pragma once\n#include \"quake_history.h\"\n\n"
                f"static const char *const kQuakeSnapshotThrough = \"{through}T00:00:00\";\n"
                f"static constexpr int kQuakeSnapshotCount = {len(lines)};\n"
                "static const char *const kQuakeSnapshotNames[] = {\n")
        f.writelines(f'"{n}",\n' for n in names)
        f.write("};\nstatic const QuakeSnapshotRow kQuakeSnapshot[] = {\n")
        f.write("\n".join(lines))
        f.write("\n};\n")
    print(f"{len(lines)} rows, {len(names)} names, through {through}")


if __name__ == "__main__":
    main()
